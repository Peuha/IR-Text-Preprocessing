# ----------------------------------------------------------------------
# Step 2: Tokenization
# ----------------------------------------------------------------------
TOKEN_RE = re.compile(
    r"""
    (?P<abbr>(?<![A-Za-z])[A-Za-z](?:\.[A-Za-z])+\.?)  # abbreviations: U.S.A. / U.S.A
  | (?P<hyph>[A-Za-z0-9]+(?:-[A-Za-z0-9]+)+)        # hyphenated: state-of-the-art
  | (?P<word>[A-Za-z0-9]+(?:['\u2019][A-Za-z]+)?)   # words, optional 's / don't
    """,
    re.VERBOSE,
)


def tokenize(text):
    """Split text into tokens; punctuation is dropped, abbreviations and
    hyphenated words stay as one token, possessive 's is removed."""
    tokens = []
    for m in TOKEN_RE.finditer(text):
        tok = m.group()
        if m.lastgroup == "abbr":
            tok = tok.replace(".", "")              # U.S.A. -> USA
        elif m.lastgroup == "word":
            tok = re.sub(r"['\u2019]s$", "", tok)   # John's -> John
        tokens.append(tok)
    return tokens


# ----------------------------------------------------------------------
# Step 3a: Normalization
# ----------------------------------------------------------------------
def normalize(tokens):
    return [t.lower() for t in tokens]


# ----------------------------------------------------------------------
# Step 3b: Stop-word removal
# ----------------------------------------------------------------------
def remove_stop_words(tokens):
    return [t for t in tokens if t not in STOP_WORDS]


# ----------------------------------------------------------------------
# Step 3c: Stemming (own implementation of the Porter algorithm)
# ----------------------------------------------------------------------
class PorterStemmer:
    STEP2 = {
        "ational": "ate", "tional": "tion", "enci": "ence", "anci": "ance",
        "izer": "ize", "abli": "able", "alli": "al", "entli": "ent",
        "eli": "e", "ousli": "ous", "ization": "ize", "ation": "ate",
        "ator": "ate", "alism": "al", "iveness": "ive", "fulness": "ful",
        "ousness": "ous", "aliti": "al", "iviti": "ive", "biliti": "ble",
    }
    STEP3 = {
        "icate": "ic", "ative": "", "alize": "al", "iciti": "ic",
        "ical": "ic", "ful": "", "ness": "",
    }
    STEP4 = ["al", "ance", "ence", "er", "ic", "able", "ible", "ant", "ement",
             "ment", "ent", "ion", "ou", "ism", "ate", "iti", "ous", "ive",
             "ize"]

    @staticmethod
    def _cons(w, i):
        c = w[i]
        if c in "aeiou":
            return False
        if c == "y":
            return i == 0 or not PorterStemmer._cons(w, i - 1)
        return True

    def _m(self, s):
        """Measure: number of VC sequences in s."""
        form = "".join("c" if self._cons(s, i) else "v" for i in range(len(s)))
        collapsed = re.sub(r"(.)\1+", r"\1", form)
        return collapsed.count("vc")

    def _has_vowel(self, s):
        return any(not self._cons(s, i) for i in range(len(s)))

    def _double_c(self, w):
        return len(w) >= 2 and w[-1] == w[-2] and self._cons(w, len(w) - 1)

    def _cvc(self, w):
        return (len(w) >= 3 and self._cons(w, len(w) - 3)
                and not self._cons(w, len(w) - 2)
                and self._cons(w, len(w) - 1) and w[-1] not in "wxy")

    def _apply(self, w, rules, min_m):
        """Longest matching suffix wins (applied only if m(stem) > min_m)."""
        for suf in sorted(rules, key=len, reverse=True):
            if w.endswith(suf):
                stem = w[: -len(suf)]
                if self._m(stem) > min_m:
                    return stem + rules[suf]
                return w
        return w

    def stem(self, w):
        if len(w) <= 2:
            return w
        # Step 1a
        if w.endswith("sses"):
            w = w[:-2]
        elif w.endswith("ies"):
            w = w[:-2]
        elif w.endswith("ss"):
            pass
        elif w.endswith("s"):
            w = w[:-1]
        # Step 1b
        if w.endswith("eed"):
            if self._m(w[:-3]) > 0:
                w = w[:-1]
        else:
            for suf in ("ed", "ing"):
                if w.endswith(suf) and self._has_vowel(w[: -len(suf)]):
                    w = w[: -len(suf)]
                    if w.endswith(("at", "bl", "iz")):
                        w += "e"
                    elif self._double_c(w) and w[-1] not in "lsz":
                        w = w[:-1]
                    elif self._m(w) == 1 and self._cvc(w):
                        w += "e"
                    break
        # Step 1c
        if w.endswith("y") and self._has_vowel(w[:-1]):
            w = w[:-1] + "i"
        # Steps 2 and 3
        w = self._apply(w, self.STEP2, 0)
        w = self._apply(w, self.STEP3, 0)
        # Step 4
        for suf in sorted(self.STEP4, key=len, reverse=True):
            if w.endswith(suf):
                stem = w[: -len(suf)]
                ok = self._m(stem) > 1
                if suf == "ion":
                    ok = ok and stem.endswith(("s", "t"))
                if ok:
                    w = stem
                break
        # Step 5
        if w.endswith("e"):
            stem = w[:-1]
            m = self._m(stem)
            if m > 1 or (m == 1 and not self._cvc(stem)):
                w = stem
        if self._m(w) > 1 and self._double_c(w) and w.endswith("l"):
            w = w[:-1]
        return w


STEMMER = PorterStemmer()


def stem_tokens(tokens):
    return [STEMMER.stem(t) for t in tokens]


# ----------------------------------------------------------------------
# Full pipeline
# ----------------------------------------------------------------------
def preprocess_trace(text):
    """Run the pipeline and keep the output of every stage (for error analysis)."""
    stages = {}
    stages["1_tokens"] = tokenize(text)
    stages["2_normalized"] = normalize(stages["1_tokens"])
    stages["3_no_stopwords"] = remove_stop_words(stages["2_normalized"])  # BEFORE stemming
    stages["4_stemmed"] = stem_tokens(stages["3_no_stopwords"])
    # The final output keeps the order of appearance AND the repeats
    # (like a token sequence in indexing). Duplicates only disappear
    # in the evaluation, where terms are compared as sets.
    return stages


def preprocess(text):
    return preprocess_trace(text)["4_stemmed"]


def print_trace(text):
    """Show what each stage did, plus how much stemming shrank the term set."""
    st = preprocess_trace(text)
    for name, toks in st.items():
        print(f"  {name:<15}: {toks}")
    before = len(set(st["3_no_stopwords"]))
    after = len(set(st["4_stemmed"]))
    print(f"  distinct terms before stemming: {before}, after: {after}")


# ----------------------------------------------------------------------
# Evaluation
# ----------------------------------------------------------------------
def evaluate(output, gold):
    O, G = set(output), set(gold)
    inter = O & G
    precision = len(inter) / len(O) if O else 0.0
    recall = len(inter) / len(G) if G else 0.0
    return precision, recall, sorted(O - G), sorted(G - O)


