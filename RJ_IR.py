def run_gui(port=8765):
    from http.server import BaseHTTPRequestHandler, HTTPServer
    import webbrowser

    class Handler(BaseHTTPRequestHandler):
        def _send(self, body, ctype):
            data = body.encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", ctype + "; charset=utf-8")
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)

        def do_GET(self):
            if self.path == "/evaluate":
                res = {}
                for name, text in TEXTS.items():
                    p, r, extra, missing = evaluate(preprocess(text), GOLD[name])
                    res[name] = {"precision": p, "recall": r,
                                 "extra": extra, "missing": missing}
                self._send(json.dumps(res), "application/json")
            else:
                page = GUI_HTML.replace("__SAMPLES__", json.dumps(TEXTS))
                self._send(page, "text/html")

        def do_POST(self):
            n = int(self.headers.get("Content-Length", 0))
            req = json.loads(self.rfile.read(n).decode("utf-8"))
            result = preprocess_trace(req["text"])
            gold = req.get("gold", "").replace(",", " ").split()
            if gold:  # Precision/Recall only when the user typed a gold standard
                p, r, extra, missing = evaluate(result["4_stemmed"], gold)
                result["evaluation"] = {"precision": p, "recall": r,
                                        "extra": extra, "missing": missing}
            self._send(json.dumps(result), "application/json")

        def log_message(self, *args):
            pass

    server = HTTPServer(("127.0.0.1", port), Handler)
    url = f"http://127.0.0.1:{port}"
    print(f"GUI running at {url}  (press Ctrl+C to stop)")
    webbrowser.open(url)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nStopped.")


